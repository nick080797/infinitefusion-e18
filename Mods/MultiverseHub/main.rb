#==============================================================================
# Multiverse Hub - "Change Game" PC menu + gauntlet zone framework
#
# Adds a PC option that warps the player into a small hand-built "gauntlet"
# zone for an integrated source game. Each zone is built as a fully synthetic
# RPG::Map object at runtime - no .rxdata file on disk - using the exact
# technique proven out by GhostBase_PlayerHousing/main.rb:
#   1. A custom tileset image is painted at runtime and registered into
#      $data_tilesets under a dedicated tileset id.
#   2. A `load_data` intercept returns a hand-built RPG::Map instead of
#      reading a Map###.rxdata file whenever the engine asks for one of our
#      reserved map ids.
#   3. `pbLoadMapInfos` is hooked so the new map id is recognized as valid.
#   4. PokemonMapFactory#updateMapsInternal and TilemapRenderer#
#      check_if_screen_moved are hooked so the engine doesn't try to load
#      real "connected" neighbor maps around our isolated zone.
#   5. Warping in/out reuses the standard Essentials transfer API
#      ($game_temp.player_new_map_id + $scene.transfer_player).
#
# This is phase 1 of the "Multiverse Hub" plan (play all 63 source games
# from one PC menu): the hub mechanism + ONE pilot gauntlet (Animon), proving
# the pattern before it's rolled out to the other ~58 GBA hacks. Nothing here
# touches any base game or AnimeFusionMerge file - fully additive.
#
# Pilot content note: Animon's dedicated boss roster (13 trainers: 8 gym
# leaders + 4 Elite Four + Champion) is already used by AnimeFusionMerge's
# GymBossPlacement.rb inside the real Kanto gym rooms, so this pilot doesn't
# duplicate those NPCs. It also still has the original two fixed encounter
# tiles (Naruto/Kuramamode) via pbWildBattle, the same technique
# AnimeFusionMerge's own LegendaryEncounters.rb uses.
#
# Second playtest pass (2026-09-03): "the animon area is too small ... needs
# to include all trainers, and a section to encounter all pokemon from each
# location type." Rather than placing ~737 individual trainer sprites (or
# ~200 wild-encounter tiles) on one map, both are exposed through two
# stationary action-button kiosk NPCs that open a class/species menu:
#   - "Trainer Hall": every real Animon trainer (Mods/AnimeFusionMerge/
#     animon_trainers.txt, generated by tools/gba_pipeline/
#     build_animon_trainers.py from the extracted ROM trainer table),
#     grouped by trainer class, battled via the standard pbTrainerBattle API.
#   - "Wild Zone": every real Animon wild species, deduped and grouped by
#     encounter method/location type (grass/water/fish/rock - see
#     animon_species_pools.rb, generated by the same script from
#     encounters.json), battled via pbWildBattle at a flat bonus-content level.
# Both kiosks are read live off whatever Bootstrap.rb/animon_species_pools.rb
# actually registered, so they can't drift out of sync with the PBS data.
#==============================================================================
module MultiverseHubSettings
  # Reserved id ranges, clear of vanilla/AFM/DigimonTrials/PlayerHousing (999).
  GAUNTLET_TILESET_ID = 9500

  # :animon used to be hardcoded here (the old hand-built gauntlet, map 9501),
  # but Mods/AnimonPort (the real ROM port) registers the same key and is the
  # one meant to win - see GAMES[s::GAME_KEY] = {...} in its main.rb. Starting
  # empty makes that deterministic instead of accidental load-order behavior.
  GAMES = {}

  # id_number range Bootstrap.rb#install registers all of animon_trainers.txt
  # under (id_number_base: 9_100_000, 737 entries) - see build_animon_trainers.py.
  ANIMON_TRAINER_ID_RANGE = (9_100_000..9_100_999)
  # Flat battle level used by the Wild Zone kiosk's "encounter any species of
  # this type" battles - this is bonus/dex-completion content, not part of
  # the game's balanced level curve, so one flat number for every species
  # keeps it simple rather than trying to derive a per-species level.
  ANIMON_WILD_ZONE_LEVEL = 30

  # Other mods (PIF2Port) push additional isolated map id => display name
  # entries here when they register far more real maps than deserve their
  # own top-level PC menu entry - e.g. PIF2Port shows ONE "Infinite Fusion 2"
  # entry in GAMES (its designated start map) but ports ~116 real PIF2 maps
  # total. Every one of those still needs: (a) to count as "gauntlet/virtual"
  # territory for the isolation hooks below and the pause-menu "Return to
  # Main Game" gate, and (b) a real MapInfo entry (below) so anything that
  # reads a map's name (location banners, etc.) doesn't hit a nil. Keyed by
  # name (not just a bare id list) so both needs are covered from one table.
  EXTRA_GAUNTLET_MAP_NAMES = {}

  # Other mods (PIF2Port) push raw map-connection records here, already
  # remapped to this game's offset ids, in the exact raw format the engine's
  # own Data/map_connections.dat stores: [mapA_id, edgeA, offsetA, mapB_id,
  # edgeB, offsetB] with edgeA/edgeB one of "N"/"S"/"E"/"W". Injected into
  # the real connections list by the load_data("map_connections") hook below
  # so real outdoor map-edge stitching (walking off a route's border into
  # its neighbor, not just doors) works for ported maps that have it.
  EXTRA_MAP_CONNECTIONS = []

  def self.gauntlet_map_ids
    GAMES.values.map { |g| g[:map_id] } + EXTRA_GAUNTLET_MAP_NAMES.keys
  end

  def self.all_map_names
    names = {}
    GAMES.each_value { |g| names[g[:map_id]] = g[:map_name] }
    names.merge!(EXTRA_GAUNTLET_MAP_NAMES)
    names
  end
end

module MultiverseHub
  MOD_GRAPHICS_DIR = "Mods/MultiverseHub/Graphics/Tilesets"

  # Levels raised past a live playtest report ("kuramamode's minimum lvl is
  # higher than 16"): Mods/AnimeFusionMerge/pokemon.txt has KIDNARUTO ->
  # NARUTO at Lv.16 and NARUTO -> KURAMAMODE at Lv.32, so the old fixed
  # levels (8 and 16) were both BELOW the stage they're supposed to
  # represent. :band picks which room (see ANIMON_BANDS) hosts each tile,
  # chosen so the fixed level sits inside that room's own range.
  ANIMON_ENCOUNTERS = {
    naruto:     { species: :NARUTO,     level: 18, band: 3 }, # room for levels 16-20
    kuramamode: { species: :KURAMAMODE, level: 33, band: 6 }, # room for levels 31-35
  }

  # One room per 5-level band (animon_species_bands.rb), placed side by side
  # and walked left to right - see build_animon_map.
  ANIMON_ROOM_W = 11
  ANIMON_ROOM_H = 11

  GAUNTLET_MAP_BUILDERS = {
    9501 => :build_animon_map
  }

  #-- Map/tileset registration ------------------------------------------------

  def self.ensure_map_infos
    mapinfos = pbLoadMapInfos rescue nil
    MultiverseHubSettings.all_map_names.each do |map_id, map_name|
      if mapinfos && !mapinfos[map_id]
        info = RPG::MapInfo.new
        info.name = map_name
        info.parent_id = 0
        info.order = 999
        mapinfos[map_id] = info
      end
      if defined?($data_mapinfos) && $data_mapinfos.is_a?(Hash) && !$data_mapinfos[map_id]
        info = RPG::MapInfo.new
        info.name = map_name
        info.parent_id = 0
        info.order = 999
        $data_mapinfos[map_id] = info
      end
    end
  end

  def self.ensure_tileset
    return unless defined?($data_tilesets)
    ts_id = MultiverseHubSettings::GAUNTLET_TILESET_ID
    return if $data_tilesets[ts_id]

    # Not using FileUtils.mkdir_p here - this build's embedded Ruby doesn't
    # ship the fileutils stdlib (LoadError at boot). Build the path up one
    # directory at a time with plain Dir.mkdir instead.
    parts = MOD_GRAPHICS_DIR.split('/')
    path = ""
    parts.each do |part|
      path = path.empty? ? part : "#{path}/#{part}"
      Dir.mkdir(path) if !Dir.exist?(path)
    end rescue nil

    # 8 distinct tiles, one per 32px column - a live playtest report ("there
    # is no grass area, just what seems to be a green ground") was caused by
    # the old floor (384) and "encounter patch" (386) using two very close
    # shades of green. Every terrain now gets its own clearly different
    # color instead of a single ambiguous green.
    bmp = Bitmap.new(256, 32)
    bmp.fill_rect(0,   0, 32, 32, Color.new(210, 190, 140)) # 384: room floor/path
    bmp.fill_rect(32,  0, 32, 32, Color.new(90,  70,  50))  # 385: wall (room border)
    bmp.fill_rect(64,  0, 32, 32, Color.new(220, 190, 60))  # 386: fixed legendary encounter tile
    bmp.fill_rect(96,  0, 32, 32, Color.new(60,  150, 50))  # 387: grass encounter tile
    bmp.fill_rect(128, 0, 32, 32, Color.new(60,  120, 200)) # 388: water encounter tile
    bmp.fill_rect(160, 0, 32, 32, Color.new(30,  90,  110)) # 389: fishing spot tile
    bmp.fill_rect(192, 0, 32, 32, Color.new(140, 130, 120)) # 390: rock smash tile
    bmp.fill_rect(224, 0, 32, 32, Color.new(160, 150, 130)) # 391: room-divider stripe
    cache_name = "Gauntlet_Shared"
    bmp.save_to_png("#{MOD_GRAPHICS_DIR}/#{cache_name}.png")
    bmp.dispose

    ts = RPG::Tileset.new
    ts.id = ts_id
    ts.name = "Multiverse Hub Gauntlet"
    # Mirrors GhostBase_PlayerHousing's path-escape convention for tileset
    # art that lives under Mods/ rather than the base Graphics/Tilesets/.
    ts.tileset_name = "../../Mods/MultiverseHub/Graphics/Tilesets/#{cache_name}"
    ts.passages = Table.new(480)
    ts.priorities = Table.new(480)
    (384..391).each { |i| ts.passages[i] = 0; ts.priorities[i] = 0 }
    ts.passages[385] = 0x0f  # wall: impassable; everything else stays passable
    $data_tilesets[ts_id] = ts
  end

  #-- Virtual map construction -------------------------------------------------

  # Third playtest pass (2026-09-03): "the animon area needs to be
  # separated... separate the mons by every 5 levels per room in the
  # gauntlet, every room need each encounter type of terrain." Replaces the
  # old single small room + menu-based "Wild Zone" kiosk with a row of real
  # walkable rooms, one per ANIMON_BANDS entry (animon_species_bands.rb,
  # real per-species level ranges from encounters.json bucketed into 5-level
  # bands), each containing all 4 terrain tiles (grass/water/fish/rock) as
  # touch-to-battle tiles instead of a menu. Rooms are walked left to right;
  # each is ANIMON_ROOM_W x ANIMON_ROOM_H with its own outer wall, so
  # crossing into the next room always happens through open floor, never a
  # doorway that could be mis-carved into a wall.
  def self.build_animon_map
    ensure_tileset
    bands = defined?(ANIMON_BANDS) && !ANIMON_BANDS.empty? ? ANIMON_BANDS :
      [{ range: 1..5, grass: [], water: [], fish: [], rock: [] }] # guard: animon_species_bands.rb didn't load
    g = MultiverseHubSettings::GAMES[:animon]
    rw, rh = ANIMON_ROOM_W, ANIMON_ROOM_H
    w, h = bands.length * rw, rh
    map = RPG::Map.new(w, h)
    map.tileset_id = MultiverseHubSettings::GAUNTLET_TILESET_ID

    (0...h).each do |y|
      (0...w).each do |x|
        local_x = x % rw
        last_room = (x / rw) == bands.length - 1
        outer_edge = (y == 0 || y == h - 1) ||
                     (x == 0 && local_x == 0) ||
                     (last_room && local_x == rw - 1)
        divider = !last_room && local_x == rw - 1
        map.data[x, y, 0] = outer_edge ? 385 : (divider ? 391 : 384)
      end
    end

    events = {}
    ev_id = 1

    add_event = lambda do |x, y, name, trigger, script_call, character_name = nil|
      ev = RPG::Event.new(x, y)
      ev.id = ev_id
      ev.name = name
      ev.pages[0].trigger = trigger
      ev.pages[0].list = [
        RPG::EventCommand.new(355, 0, [script_call]),
        RPG::EventCommand.new(0, 0, []),
      ]
      if character_name
        # Kiosk NPCs need a visible sprite or the map just reads as empty
        # grass - found via live playtest ("the animon area... is too small",
        # then after the expansion, "the animon gauntlet map is empty").
        ev.pages[0].graphic.character_name = character_name
        ev.pages[0].graphic.direction = 2 # facing down
      end
      events[ev_id] = ev
      ev_id += 1
    end

    add_event.call(g[:spawn][0], g[:spawn][1] - 1, "MVHub_Exit", 1, "MultiverseHub.return_to_overworld")
    # Trainer Hall stays a single kiosk in the first room - the full 737-
    # trainer roster isn't level-banded (trainer teams already carry their
    # own real levels), so it doesn't need one copy per room.
    add_event.call(5, 1, "MVHub_Animon_TrainerHall", 0, "MultiverseHub.animon_trainer_hall", "BWClerk")

    terrain_tiles = { grass: [387, 2, 3], water: [388, 8, 3], fish: [389, 2, 7], rock: [390, 8, 7] }
    bands.each_with_index do |band, i|
      x_base = i * rw
      terrain_tiles.each do |terrain, (tile_id, lx, ly)|
        next if (band[terrain] || []).empty?
        map.data[x_base + lx, ly, 0] = tile_id
        add_event.call(x_base + lx, ly, "MVHub_Animon_B#{i}_#{terrain}", 1,
                        "MultiverseHub.trigger_animon_band_encounter(#{i}, :#{terrain})")
      end
    end
    # Fixed legendary tiles (Naruto/Kuramamode) sit inside whichever band
    # room their (now evolution-accurate) level actually belongs to.
    ANIMON_ENCOUNTERS.each do |id, data|
      x_base = data[:band] * rw
      map.data[x_base + 5, 5, 0] = 386
      add_event.call(x_base + 5, 5, "MVHub_Animon_#{id.to_s.capitalize}", 1,
                      "MultiverseHub.trigger_animon_encounter(:#{id})")
    end

    map.events = events
    map
  end

  #-- Battle triggers -----------------------------------------------------

  def self.trigger_animon_encounter(id)
    data = ANIMON_ENCOUNTERS[id]
    return unless data
    return unless GameData::Species.exists?(data[:species])
    $PokemonGlobal.mvhub_animon_cleared ||= {}
    if $PokemonGlobal.mvhub_animon_cleared[id]
      pbMessage(_INTL("The grass here has gone quiet. You've already cleared this spot."))
      return
    end
    pbMessage(_INTL("A wild presence stirs in the grass..."))
    won = pbWildBattle(data[:species], data[:level])
    return unless won
    $PokemonGlobal.mvhub_animon_cleared[id] = true
    if $PokemonGlobal.mvhub_animon_cleared.size >= ANIMON_ENCOUNTERS.size
      pbMessage(_INTL("You've cleared the Animon Gauntlet! (pilot)"))
    else
      pbMessage(_INTL("The gauntlet's path grows clearer..."))
    end
  end

  # Repeatable per-room terrain encounter - species pool and level range both
  # come straight from ANIMON_BANDS[band_idx] (real ROM data for that 5-level
  # band; a terrain with no real data that band reuses its nearest lower
  # band's list, see build_animon_bands.py), so unlike the two fixed
  # legendary tiles this one can be battled more than once.
  def self.trigger_animon_band_encounter(band_idx, terrain)
    band = defined?(ANIMON_BANDS) ? ANIMON_BANDS[band_idx] : nil
    return unless band
    species_list = band[terrain] || []
    return if species_list.empty?
    species = species_list[rand(species_list.length)]
    return unless GameData::Species.exists?(species)
    range = band[:range]
    level = range.first + rand(range.last - range.first + 1)
    pbMessage(_INTL("A wild presence stirs in the {1}...", terrain.to_s))
    pbWildBattle(species, level)
  end

  #-- Trainer Hall: every real Animon trainer, grouped by class ------------

  def self.animon_trainers_by_class
    return @animon_trainers_by_class if @animon_trainers_by_class
    grouped = {}
    GameData::Trainer.each do |t|
      next unless MultiverseHubSettings::ANIMON_TRAINER_ID_RANGE.include?(t.id_number)
      (grouped[t.trainer_type] ||= []) << t
    end
    grouped.each_value { |list| list.sort_by! { |t| [t.real_name, t.version] } }
    @animon_trainers_by_class = grouped
  end

  def self.animon_trainer_hall
    grouped = animon_trainers_by_class
    if grouped.empty?
      pbMessage(_INTL("The trainer hall is empty. (No Animon trainers registered.)"))
      return
    end
    classes = grouped.keys.sort_by { |sym| (GameData::TrainerType.try_get(sym)&.name || sym.to_s) }
    labels = classes.map { |sym| "#{GameData::TrainerType.try_get(sym)&.name || sym} (#{grouped[sym].length})" }
    labels.push(_INTL("Cancel"))
    loop do
      choice = pbMessage(_INTL("Whose trainers would you like to challenge?"), labels, labels.length)
      break if !choice || choice < 0 || choice >= classes.length
      cls = classes[choice]
      roster = grouped[cls]
      names = roster.map { |t| "#{t.real_name} (Lv.#{t.pokemon[0] ? t.pokemon[0][:level] : "?"})" }
      names.push(_INTL("Back"))
      inner_choice = pbMessage(_INTL("Challenge which trainer?"), names, names.length)
      next if !inner_choice || inner_choice < 0 || inner_choice >= roster.length
      trainer = roster[inner_choice]
      pbTrainerBattle(trainer.trainer_type, trainer.real_name, nil, false, trainer.version, true)
    end
  end

  #-- Wild Zone: every real Animon wild species, grouped by location type --

  def self.animon_wild_zone
    pools = defined?(ANIMON_SPECIES_POOLS) ? ANIMON_SPECIES_POOLS : {}
    labels = [
      [:grass, _INTL("Grass")], [:water, _INTL("Water")],
      [:fish,  _INTL("Fishing")], [:rock, _INTL("Rock Smash")],
    ]
    menu = labels.map { |key, label| "#{label} (#{(pools[key] || []).length})" }
    menu.push(_INTL("Cancel"))
    loop do
      choice = pbMessage(_INTL("Which kind of location would you like to search?"), menu, menu.length)
      break if !choice || choice < 0 || choice >= labels.length
      key = labels[choice][0]
      species_list = pools[key] || []
      if species_list.empty?
        pbMessage(_INTL("Nothing seems to live there."))
        next
      end
      names = species_list.map { |sp| GameData::Species.exists?(sp) ? GameData::Species.get(sp).name : sp.to_s }
      names.push(_INTL("Back"))
      inner_choice = pbMessage(_INTL("Encounter which Pokémon?"), names, names.length)
      next if !inner_choice || inner_choice < 0 || inner_choice >= species_list.length
      species = species_list[inner_choice]
      next unless GameData::Species.exists?(species)
      pbMessage(_INTL("A wild presence stirs..."))
      pbWildBattle(species, MultiverseHubSettings::ANIMON_WILD_ZONE_LEVEL)
    end
  end

  #-- Warping ---------------------------------------------------------------

  # Ported games' own events can leave lasting screen state behind - e.g.
  # DBZInfiniteFusion's Mount Paozu has an unconditional autorun event that
  # shows a "Dragon Ball Z" logo picture and never erases it (a permanent
  # decorative watermark in the original standalone game, which never needed
  # to hand control to any other game afterward). $game_screen is a single
  # shared instance across every ported game in the hub, so without this the
  # logo (or any other leftover picture) stays on screen after switching to
  # a different game or returning to the main overworld. Called on every hub
  # transition, not just DBZ's, since any ported game could do the same.
  def self.clear_screen_effects!
    $game_screen.pictures.each { |p| p&.erase }
  end

  def self.enter_gauntlet(key)
    g = MultiverseHubSettings::GAMES[key]
    return unless g
    ensure_map_infos
    unless MultiverseHubSettings.gauntlet_map_ids.include?($game_map.map_id)
      $PokemonGlobal.mvhub_return_point = [$game_map.map_id, $game_player.x, $game_player.y, $game_player.direction]
    end
    x, y, dir = g[:spawn]
    pbFadeOutIn do
      clear_screen_effects!
      $game_temp.player_transferring = true
      $game_temp.transition_processing = true
      $game_temp.player_new_map_id = g[:map_id]
      $game_temp.player_new_x = x
      $game_temp.player_new_y = y
      $game_temp.player_new_direction = dir
      $scene.transfer_player if $scene.respond_to?(:transfer_player)
    end
    # Some ported worlds spawn the player behind a MAP_DYNAMIC ("walk back
    # out the door you came in") exit, which normally only works after a
    # real warp-in stamps where "in" was. Since this teleport bypasses any
    # real warp event, pre-seed it here so that door leads into the world
    # instead of being inert or bouncing straight back to this hub.
    $gba_dynamic_warp = g[:seed_dynamic_warp] if g[:seed_dynamic_warp]
  end

  def self.return_to_overworld
    rp = $PokemonGlobal.mvhub_return_point
    rp ||= [1, 5, 5, 2]
    map_id, x, y, dir = rp
    pbFadeOutIn do
      clear_screen_effects!
      $game_temp.player_transferring = true
      $game_temp.transition_processing = true
      $game_temp.player_new_map_id = map_id
      $game_temp.player_new_x = x
      $game_temp.player_new_y = y
      $game_temp.player_new_direction = dir
      $scene.transfer_player if $scene.respond_to?(:transfer_player)
    end
  end
end

