#-- PC menu entry -------------------------------------------------------------
class MultiverseHubPC
  def shouldShow?
    true
  end

  def name
    _INTL("Change Game")
  end

  def access
    games = MultiverseHubSettings::GAMES
    commands = games.values.map { |g| g[:name] }
    in_gauntlet = MultiverseHubSettings.gauntlet_map_ids.include?($game_map.map_id)
    commands.push(_INTL("Return to overworld")) if in_gauntlet
    commands.push(_INTL("Cancel"))
    choice = pbMessage(_INTL("Which world would you like to visit?"), commands, commands.length)
    return if !choice || choice < 0 || choice >= commands.length - 1
    if in_gauntlet && choice == games.length
      MultiverseHub.return_to_overworld
    elsif choice < games.length
      key = games.keys[choice]
      MultiverseHub.enter_gauntlet(key)
    end
  end
end
PokemonPCList.registerPC(MultiverseHubPC.new)

#-- load_data interception: hand a synthetic map back for our reserved ids --
alias __mvhub_orig_load_data load_data unless defined?(__mvhub_orig_load_data)
def load_data(f)
  if f.is_a?(String)
    MultiverseHub::GAUNTLET_MAP_BUILDERS.each do |map_id, method_name|
      return MultiverseHub.send(method_name) if f.include?(sprintf("Map%03d", map_id))
    end
    if f.include?("MapInfos")
      infos = __mvhub_orig_load_data(f)
      # Patch in every registered gauntlet/virtual map id here too, not just
      # at PC-menu enter_gauntlet time - a real door/transfer event inside a
      # ported map (e.g. PIF2Port's non-PC-menu interiors) reaches its target
      # map without ever going through enter_gauntlet, so this is the one
      # place guaranteed to run before ANY of those ids are looked up.
      if infos
        MultiverseHubSettings.all_map_names.each do |map_id, map_name|
          next if infos[map_id]
          info = RPG::MapInfo.new
          info.name = map_name
          info.parent_id = 0
          info.order = 999
          infos[map_id] = info
        end
      end
      return infos
    end
    if f.include?("map_connections")
      conns = __mvhub_orig_load_data(f)
      conns += MultiverseHubSettings::EXTRA_MAP_CONNECTIONS if conns.is_a?(Array)
      return conns
    end
  end
  __mvhub_orig_load_data(f)
end

#-- pbLoadMapInfos hook: make sure our reserved map ids are always valid ----
alias __mvhub_orig_pbLoadMapInfos pbLoadMapInfos unless defined?(__mvhub_orig_pbLoadMapInfos)
def pbLoadMapInfos
  infos = __mvhub_orig_pbLoadMapInfos
  if infos
    MultiverseHubSettings.all_map_names.each do |map_id, map_name|
      next if infos[map_id]
      info = RPG::MapInfo.new
      info.name = map_name
      info.parent_id = 0
      info.order = 999
      infos[map_id] = info
    end
  end
  infos
end

#-- Keep the map factory from trying to load real "connected" neighbor maps -
class ::PokemonMapFactory
  alias __mvhub_orig_updateMapsInternal updateMapsInternal unless method_defined?(:__mvhub_orig_updateMapsInternal)
  def updateMapsInternal
    # Only isolate maps that have no REAL connection data (the synthetic
    # Animon map, PIF2 interiors) - a ported PIF2 outdoor map that DOES have
    # real map_connections.dat entries (injected via load_data above) should
    # use the engine's normal multi-map loading so walking off its edge
    # reaches its real neighbor instead of being clamped/isolated.
    if $game_map && MultiverseHubSettings.gauntlet_map_ids.include?($game_map.map_id) &&
       !MapFactoryHelper.hasConnections?($game_map.map_id)
      if @maps.length > 1
        gid = $game_map.map_id
        @maps.delete_if { |m| m && m.map_id != gid }
        @mapIndex = getMapIndex(gid)
      end
      return
    end
    __mvhub_orig_updateMapsInternal
  end
end

#-- Keep the camera from glitching across the synthetic-map boundary --------
class ::TilemapRenderer
  alias __mvhub_orig_check_if_screen_moved check_if_screen_moved unless method_defined?(:__mvhub_orig_check_if_screen_moved)
  def check_if_screen_moved
    if @current_map_id != $game_map.map_id
      # Same real-connections carve-out as updateMapsInternal above - a
      # genuinely connected ported map should scroll normally across the
      # seam, not get the synthetic-map camera reset.
      is_g  = MultiverseHubSettings.gauntlet_map_ids.include?($game_map.map_id) &&
              !MapFactoryHelper.hasConnections?($game_map.map_id)
      was_g = MultiverseHubSettings.gauntlet_map_ids.include?(@current_map_id) &&
              !MapFactoryHelper.hasConnections?(@current_map_id)
      if is_g || was_g
        @current_map_id = $game_map.map_id
        @pixel_offset_x = 0
        @pixel_offset_y = 0
        return __mvhub_orig_check_if_screen_moved
      end
    end
    __mvhub_orig_check_if_screen_moved
  end
end

#-- Pause menu entry: "Return to Main Game" from anywhere, not just a PC ----
# 016_UI_PauseMenu.rb's pbStartPokemonMenu has no extension hook (no
# EventHandlers/registration list to add a command to) - the commands array
# and its dispatch loop are both built inline in one big procedural method.
# So this can't be done with a plain alias-and-call-original wrapper the way
# the rest of this mod hooks things; the whole method has to be copied and
# re-defined with the one new command spliced in. This is an intentional,
# documented exception to the "never touch base files" rule - the file
# itself isn't touched, but this override will go stale if a future
# Essentials/host update changes 016_UI_PauseMenu.rb's pbStartPokemonMenu.
# If the pause menu ever stops matching the base game, re-diff against
# Data/Scripts/016_UI/001_UI_PauseMenu.rb and re-apply this splice.
#
# Placed "right under Debug" per the user's request, since a stray crash
# while exploring a not-yet-ported PIF2 interior could otherwise strand the
# player far from a PC with no way back to their real save.
class PokemonPauseMenu
  def pbStartPokemonMenu
    if !$Trainer
      if $DEBUG
        pbMessage(_INTL("The player trainer was not defined, so the pause menu can't be displayed."))
        pbMessage(_INTL("Please see the documentation to learn how to set up the trainer player."))
      end
      return
    end
    @scene.pbStartScene
    endscene = true
    commands = []
    cmdPokedex = -1
    cmdPokemon = -1
    cmdBag = -1
    cmdTrainer = -1
    cmdSave = -1
    cmdOption = -1
    cmdPokegear = -1
    cmdDebug = -1
    cmdMvHub = -1
    cmdQuit = -1
    cmdEndGame = -1
    if $Trainer.has_pokedex && $Trainer.pokedex.accessible_dexes.length > 0
      commands[cmdPokedex = commands.length] = "  <icon=#{ICON_POKEDEX}>  " + _INTL("Pokédex")
    end
    commands[cmdPokemon = commands.length] = "  <icon=#{ICON_POKEMON}>  " + _INTL("Pokémon") if $Trainer.party_count > 0
    commands[cmdBag = commands.length] = "  <icon=#{ICON_BAG}>  " + _INTL("Bag") if !pbInBugContest?
    commands[cmdPokegear = commands.length] = "  <icon=#{ICON_POKENAV}>  " + _INTL("PokéNav") if $Trainer.has_pokegear
    commands[cmdTrainer = commands.length] = "  <icon=#{ICON_PLAYER}>  " + _INTL("{1}", $Trainer.name)
    commands[cmdOutfit = commands.length] = "  <icon=#{ICON_OUTFIT}>  " + _INTL("Outfit") if $Trainer.can_change_outfit
    if pbInSafari?
      if Settings::SAFARI_STEPS <= 0
        @scene.pbShowInfo(_INTL("Balls: {1}", pbSafariState.ballcount))
      else
        @scene.pbShowInfo(_INTL("Steps: {1}/{2}\nBalls: {3}",
                                pbSafariState.steps, Settings::SAFARI_STEPS, pbSafariState.ballcount))
      end
      commands[cmdQuit = commands.length] = "  <icon=#{ICON_QUIT_SAFARI}>  " + _INTL("Quit")
    elsif pbInBugContest?
      if pbBugContestState.lastPokemon
        @scene.pbShowInfo(_INTL("Caught: {1}\nLevel: {2}\nBalls: {3}",
                                pbBugContestState.lastPokemon.speciesName,
                                pbBugContestState.lastPokemon.level,
                                pbBugContestState.ballcount))
      else
        @scene.pbShowInfo(_INTL("Caught: None\nBalls: {1}", pbBugContestState.ballcount))
      end
      commands[cmdQuit = commands.length] = _INTL("Quit Contest")
    else
      commands[cmdSave = commands.length] = "  <icon=#{ICON_SAVE}>  " + _INTL("Save") if $game_system && !$game_system.save_disabled
    end
    commands[cmdOption = commands.length] = "  <icon=#{ICON_OPTIONS}>  " + _INTL("Options")
    commands[cmdDebug = commands.length] = "  <icon=#{ICON_DEBUG}>  " + _INTL("Debug") if $DEBUG
    in_gauntlet = MultiverseHubSettings.gauntlet_map_ids.include?($game_map.map_id)
    commands[cmdMvHub = commands.length] = "  <icon=#{ICON_TITLE}>  " + _INTL("Return to Main Game") if in_gauntlet
    commands[cmdEndGame = commands.length] = "  <icon=#{ICON_TITLE}>  " + _INTL("Title")
    loop do
      command = @scene.pbShowCommands(commands)
      if cmdPokedex >= 0 && command == cmdPokedex
        pbPlayDecisionSE
        if Settings::USE_CURRENT_REGION_DEX
          pbFadeOutIn {
            scene = PokemonPokedex_Scene.new
            screen = PokemonPokedexScreen.new(scene)
            screen.pbStartScreen
            @scene.pbRefresh
          }
        else
          $PokemonGlobal.pokedexDex = $Trainer.pokedex.accessible_dexes[0]
          pbFadeOutIn {
            scene = PokemonPokedexMenu_Scene.new
            screen = PokemonPokedexMenuScreen.new(scene)
            screen.pbStartScreen
            @scene.pbRefresh
          }
        end
      elsif cmdPokemon >= 0 && command == cmdPokemon
        pbPlayDecisionSE
        hiddenmove = nil
        pbFadeOutIn {
          sscene = PokemonParty_Scene.new
          sscreen = PokemonPartyScreen.new(sscene, $Trainer.party)
          hiddenmove = sscreen.pbPokemonScreen
          (hiddenmove) ? @scene.pbEndScene : @scene.pbRefresh
        }
        if hiddenmove
          $game_temp.in_menu = false
          pbUseHiddenMove(hiddenmove[0], hiddenmove[1])
          return
        end
      elsif cmdBag >= 0 && command == cmdBag
        pbPlayDecisionSE
        item = nil
        pbFadeOutIn {
          scene = PokemonBag_Scene.new
          screen = PokemonBagScreen.new(scene, $PokemonBag)
          item = screen.pbStartScreen
          (item) ? @scene.pbEndScene : @scene.pbRefresh
        }
        if item
          $game_temp.in_menu = false
          pbUseKeyItemInField(item)
          return
        end
      elsif cmdPokegear >= 0 && command == cmdPokegear
        pbPlayDecisionSE
        pbFadeOutIn {
          @scene.pbHideMenu
          scene = PokemonPokegear_Scene.new
          screen = PokemonPokegearScreen.new(scene)
          screen.pbStartScreen
        }
      elsif cmdTrainer >= 0 && command == cmdTrainer
        pbPlayDecisionSE
        pbFadeOutIn {
          scene = PokemonTrainerCard_Scene.new
          screen = PokemonTrainerCardScreen.new(scene)
          screen.pbStartScreen
          @scene.pbRefresh
        }
      elsif cmdOutfit && cmdOutfit >= 0 && command == cmdOutfit
        @scene.pbHideMenu
        pbCommonEvent(COMMON_EVENT_OUTFIT)
      elsif cmdQuit >= 0 && command == cmdQuit
        @scene.pbHideMenu
        if pbInSafari?
          if pbConfirmMessage(_INTL("Would you like to leave the Safari Game right now?"))
            @scene.pbEndScene
            pbSafariState.decision = 1
            pbSafariState.pbGoToStart
            return
          else
            pbShowMenu
          end
        else
          if pbConfirmMessage(_INTL("Would you like to end the Contest now?"))
            @scene.pbEndScene
            pbBugContestState.pbStartJudging
            return
          else
            pbShowMenu
          end
        end
      elsif cmdSave >= 0 && command == cmdSave
        @scene.pbHideMenu
        scene = PokemonSave_Scene.new
        screen = PokemonSaveScreen.new(scene)
        if screen.pbSaveScreen
          @scene.pbEndScene
          endscene = false
          break
        else
          pbShowMenu
        end
      elsif cmdOption >= 0 && command == cmdOption
        pbPlayDecisionSE
        pbFadeOutIn {
          scene = PokemonGameOption_Scene.new
          screen = PokemonOptionScreen.new(scene)
          screen.pbStartScreen
          pbUpdateSceneMap
          @scene.pbRefresh
        }
      elsif cmdDebug >= 0 && command == cmdDebug
        pbPlayDecisionSE
        pbFadeOutIn {
          pbDebugMenu
          @scene.pbRefresh
        }
      elsif cmdMvHub >= 0 && command == cmdMvHub
        pbPlayDecisionSE
        if pbConfirmMessage(_INTL("Return to the main game now?"))
          @scene.pbHideMenu
          @scene.pbEndScene
          MultiverseHub.return_to_overworld
          return
        else
          pbShowMenu
        end
      elsif cmdEndGame >= 0 && command == cmdEndGame
        @scene.pbHideMenu
        if pbConfirmMessage(_INTL("Are you sure you want to quit the game and return to the main menu?"))
          scene = PokemonSave_Scene.new
          screen = PokemonSaveScreen.new(scene)
          screen.pbSaveScreen
          $game_temp.to_title = true
          return
        else
          pbShowMenu
        end
      else
        pbPlayCloseMenuSE
        break
      end
    end
    @scene.pbEndScene if endscene
  end
end

